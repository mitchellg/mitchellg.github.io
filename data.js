// Render functions
function renderPublications(category = 'all') {
    const container = document.getElementById('publications-list');
    if (!container) return;
    
    let previousYear = null;
    const visible = publications.filter(pub => category === 'all' || pub.categories.includes(category));
    container.innerHTML = visible.map(pub => {
        const yearHeading = pub.year !== previousYear ? `<h4 class="publication-year">${pub.year}</h4>` : '';
        previousYear = pub.year;
        const authorsList = pub.authors.join(', ');
        
        const award = pub.award ? ` <span class="award">${pub.award}</span>` : '';
        const titleLink = pub.url ? `<a href="${pub.url}">${pub.title}</a>` : pub.title;
        const venueWithYear = pub.year ? `${pub.venue}, ${pub.year}` : pub.venue;
        
        return `
            ${yearHeading}
            <div class="publication">
                <p class="pub-title">${titleLink}</p>
                <p class="pub-authors">${authorsList}</p>
                <p class="pub-venue"><i>${venueWithYear}</i>${award}</p>
            </div>
        `;
    }).join('');
}

function renderStudents(type = 'phd', containerId = 'students-list') {
    const container = document.getElementById(containerId);
    if (!container) return;
    
    container.innerHTML = students.filter(student => student.type === type).map(student => {
        const nameLink = student.website ? `<a href="${student.website}">${student.name}</a>` : student.name;
        
        let imageHtml;
        if (student.image) {
            const imageTag = `<img src="${student.image}" alt="${student.name}" class="student-photo">`;
            imageHtml = student.website ? `<a href="${student.website}">${imageTag}</a>` : imageTag;
        } else {
            imageHtml = `<div class="student-photo-placeholder"></div>`;
        }
        
        return `
            <div class="student-item">
                ${imageHtml}
                <p class="student-name">${nameLink}${student.note ? `<span class="student-note">${student.note}</span>` : ''}</p>
            </div>
        `;
    }).join('');
}

function renderTeaching() {
    const container = document.getElementById('teaching-list');
    if (!container) return;
    
    container.innerHTML = teaching.map(item => {
        const courseLink = item.url ? `<a href="${item.url}">${item.course}</a>` : item.course;
        return `
            <div class="teaching-item">
                <p><strong>${item.term}</strong> ${item.role}, ${courseLink}, ${item.institution}</p>
            </div>
        `;
    }).join('');
}


// Native buttons retain normal keyboard activation; arrow keys switch tabs.
function setupPublicationTabs() {
    const tablist = document.getElementById('publication-tabs');
    const panel = document.getElementById('publications-list');
    const tabs = Array.from(tablist.querySelectorAll('[role="tab"]'));
    function select(tab) {
        tabs.forEach(item => {
            const active = item === tab;
            item.setAttribute('aria-selected', String(active));
            item.tabIndex = active ? 0 : -1;
        });
        panel.setAttribute('aria-labelledby', tab.id);
        renderPublications(tab.dataset.category);
    }
    tabs.forEach((tab, index) => {
        tab.addEventListener('click', () => select(tab));
        tab.addEventListener('keydown', event => {
            let next;
            if (event.key === 'ArrowRight') next = (index + 1) % tabs.length;
            else if (event.key === 'ArrowLeft') next = (index - 1 + tabs.length) % tabs.length;
            else if (event.key === 'Home') next = 0;
            else if (event.key === 'End') next = tabs.length - 1;
            else return;
            event.preventDefault();
            select(tabs[next]);
            tabs[next].focus();
        });
    });
}

